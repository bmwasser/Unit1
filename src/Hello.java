public class Hello {
    
    public static void main(String[] args) {
        final double PI = 3.14159265358979;
        final double TAU = 2 * PI; 
        System.out.printf("Pi to 4 decimal places is: %.2f\n", PI );
        System.out.printf("Pi as a whole number is: %.0f\n", PI);
        System.out.printf("Pi is %.2f and Tau is %.2f",PI,TAU);
    }
}
